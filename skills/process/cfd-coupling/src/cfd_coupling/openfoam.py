@dataclass
class VofOpenFoamCase(_FoamCaseBase):
    """A transient volume-of-fluid case for two phases from one NeqSim flash.

    Volume of fluid resolves the interface, so it answers stratified, slug, annular
    and free-surface questions. It is the wrong tool for a dilute droplet mist: the
    multiphase screening says so, and this class refuses to build a case the
    screening did not recommend unless that is explicitly overridden.
    """

    boundary: MultiphaseBoundaryConditions
    mesh: MeshSpec
    name: str = "neqsim_vof_case"
    flavour: str = "org"
    end_time: float = 5.0
    write_interval: float = 0.25
    max_courant: float = 0.5
    max_alpha_courant: float = 0.5
    initial_time_step: float = 1.0e-4
    wall_treatment: str = "wall_function"
    inlet_patch: str = "inlet"
    outlet_patch: str = "outlet"
    wall_patches: Sequence[str] = ("walls",)
    axis: str = "z"
    gravity: tuple[float, float, float] = (0.0, -GRAVITY_M_PER_S2, 0.0)
    initial_dispersed_fraction: float = 0.0
    allow_unrecommended_model: bool = False
    extra_notes: Sequence[str] = field(default_factory=tuple)

    def __post_init__(self) -> None:
        self._validate_common()
        if not 0.0 <= self.initial_dispersed_fraction <= 1.0:
            raise ValueError("initial_dispersed_fraction must lie between 0 and 1")
        if self.boundary.recommended_model != "vof" and not self.allow_unrecommended_model:
            raise ValueError(
                "the multiphase screening recommended "
                f"'{self.boundary.recommended_model}', not volume of fluid: "
                f"{self.boundary.model_rationale} Pass allow_unrecommended_model=True to "
                "build the case anyway and record the reason."
            )

    @property
    def dispersed_name(self) -> str:
        """OpenFOAM phase name for the tracked (alpha) phase."""
        return _foam_name(self.boundary.state.dispersed.phase)

    @property
    def continuous_name(self) -> str:
        """OpenFOAM phase name for the carrier phase."""
        return _foam_name(self.boundary.state.continuous.phase)

    def commands(self) -> tuple[str, ...]:
        """Return the ordered shell commands that mesh, initialise and solve."""
        spec = _FLAVOURS[self.flavour]
        steps = self._mesh_commands()
        steps.append("setFields")
        steps.append(spec["vof_application"])
        steps.append("foamToVTK -latestTime")
        return tuple(steps)

