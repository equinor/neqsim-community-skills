def read_case_results(
    case_dir: str | Path, *, density_kg_per_m3: float | None = None
) -> OpenFoamResults:
    """Read the function-object output of a solved case into engineering numbers.

    Incompressible OpenFOAM reports kinematic pressure and kinematic wall shear
    (m2/s2). When ``density_kg_per_m3`` is supplied they are converted to Pa, which
    is what a receiving corrosion, erosion or pressure-drop model expects. A volume
    of fluid case already reports ``p_rgh`` in Pa, so leave the density out for it.
    """
    root = Path(case_dir) / "postProcessing"
    findings: list[str] = []

    if not root.is_dir():
        return OpenFoamResults(
            None, None, None, None, None, None, None, None, None, None,
            ("No postProcessing directory; the case has not produced results yet.",),
        )

    inlet_flux = _scalar_result(root, "inletFlux")
    outlet_flux = _scalar_result(root, "outletFlux")
    inlet_pressure = _scalar_result(root, "inletPressure")
    outlet_pressure = _scalar_result(root, "outletPressure")
    peak_shear = _magnitude_result(root, prefix="peakWallShear")
    mean_shear = _magnitude_result(root, prefix="meanWallShear")
    dispersed_fraction = _scalar_result(root, "outletDispersedFraction")
    y_plus = _y_plus_result(root)

    continuity = None
    inlet_volumetric = abs(inlet_flux) if inlet_flux is not None else None
    outlet_volumetric = abs(outlet_flux) if outlet_flux is not None else None
    if inlet_volumetric and outlet_volumetric:
        continuity = abs(outlet_volumetric - inlet_volumetric) / inlet_volumetric
        if continuity > 0.01:
            findings.append(
                f"Inlet and outlet volumetric flow differ by {100.0 * continuity:.2f} %; "
                "the solution is not converged on continuity."
            )

    pressure_drop = None
    if inlet_pressure is not None and outlet_pressure is not None:
        pressure_drop = inlet_pressure - outlet_pressure
        if density_kg_per_m3:
            pressure_drop *= density_kg_per_m3
        else:
            findings.append(
                "Pressure drop is reported as read; supply density_kg_per_m3 to convert "
                "a kinematic (m2/s2) incompressible pressure to Pa."
            )

    if density_kg_per_m3:
        peak_shear = peak_shear * density_kg_per_m3 if peak_shear is not None else None
        mean_shear = mean_shear * density_kg_per_m3 if mean_shear is not None else None
    elif peak_shear is not None:
        findings.append("Wall shear is kinematic (m2/s2); supply density_kg_per_m3 to obtain Pa.")

    if y_plus:
        findings.append(
            f"Wall resolution: y+ min {y_plus[0]:.2f}, mean {y_plus[1]:.2f}, max {y_plus[2]:.2f}. "
            "Feed these into the quality gate before using any local value."
        )
    if dispersed_fraction is not None:
        findings.append(
            f"Outlet dispersed-phase fraction {dispersed_fraction:.4g}; compare it with the "
            "inlet flash split to judge whether the phases separated in the geometry."
        )

    return OpenFoamResults(
        inlet_volumetric_flow_m3_per_s=inlet_volumetric,
        outlet_volumetric_flow_m3_per_s=outlet_volumetric,
        continuity_error_relative=continuity,
        pressure_drop_pa=pressure_drop,
        peak_wall_shear_pa=peak_shear,
        mean_wall_shear_pa=mean_shear,
        y_plus_min=y_plus[0] if y_plus else None,
        y_plus_mean=y_plus[1] if y_plus else None,
        y_plus_max=y_plus[2] if y_plus else None,
        outlet_dispersed_fraction=dispersed_fraction,
        findings=tuple(findings),
    )


def _latest_data_file(root: Path, name: str, filename: str) -> Path | None:
    directory = root / name
    if not directory.is_dir():
        return None
    candidates = sorted(
        (path for path in directory.glob(f"*/{filename}") if path.is_file()),
        key=lambda path: _time_key(path.parent.name),
    )
    return candidates[-1] if candidates else None


def _time_key(name: str) -> float:
    try:
        return float(name)
    except ValueError:
        return -1.0


def _last_row(path: Path) -> list[str] | None:
    rows = [
        line.strip()
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines()
        if line.strip() and not line.lstrip().startswith("#")
    ]
    if not rows:
        return None
    return _tokenise(rows[-1])


def _tokenise(row: str) -> list[str]:
    """Split a data row, keeping parenthesised vectors as single tokens."""
    return re.findall(r"\([^)]*\)|\S+", row)


def _scalar_result(root: Path, name: str) -> float | None:
    path = _latest_data_file(root, name, "surfaceFieldValue.dat")
    if path is None:
        return None
    tokens = _last_row(path)
    if not tokens or len(tokens) < 2:
        return None
    return _as_magnitude(tokens[-1])


def _magnitude_result(root: Path, *, prefix: str) -> float | None:
    values = []
    for directory in sorted(root.glob(f"{prefix}*")):
        path = _latest_data_file(root, directory.name, "surfaceFieldValue.dat")
        if path is None:
            continue
        tokens = _last_row(path)
        if tokens and len(tokens) >= 2:
            value = _as_magnitude(tokens[-1])
            if value is not None:
                values.append(value)
    return max(values) if values else None


def _y_plus_result(root: Path) -> tuple[float, float, float] | None:
    path = _latest_data_file(root, "yPlus", "yPlus.dat")
    if path is None:
        return None
    minima: list[float] = []
    maxima: list[float] = []
    averages: list[float] = []
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        tokens = line.split()
        if len(tokens) < 5:
            continue
        try:
            minima.append(float(tokens[-3]))
            maxima.append(float(tokens[-2]))
            averages.append(float(tokens[-1]))
        except ValueError:
            continue
    if not minima:
        return None
    return min(minima), sum(averages) / len(averages), max(maxima)


def _as_magnitude(token: str) -> float | None:
    if token.startswith("("):
        try:
            components = [float(part) for part in token.strip("()").split()]
        except ValueError:
            return None
        return sum(component**2 for component in components) ** 0.5
    try:
        value = float(token)
    except ValueError:
        return None
    return value if isfinite(value) else None


def _foam_file(class_name: str, location: str, object_name: str) -> str:
    return _HEADER.format(class_name=class_name, location=location, object_name=object_name)


def _foam_name(phase: str) -> str:
    """OpenFOAM phase names appear in field names, so keep them alphanumeric."""
    cleaned = re.sub(r"[^0-9a-zA-Z]+", "", phase or "")
    return cleaned or "phase"


def _nu_entry(spec: dict[str, Any], nu: float) -> str:
    if spec["dimensioned_nu"]:
        return f"nu              [0 2 -1 0 0 0 0] {nu:.8g};"
    return f"nu              {nu:.8g};"


def _require_positive(name: str, value: float | None) -> None:
    if value is None or not isfinite(value) or value <= 0.0:
        raise ValueError(f"{name} must be a positive finite number")
