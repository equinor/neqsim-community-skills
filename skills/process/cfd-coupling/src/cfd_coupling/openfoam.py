def _channel_block_mesh(mesh: MeshSpec, inlet: str, outlet: str, wall: str) -> str:
    """Single-block rectangular duct graded towards both wall pairs."""
    height = mesh.height_m
    width = mesh.width_m
    length = mesh.length_m
    half_cells = max(1, mesh.radial_cells // 2)
    grading, cell_ratio = _wall_grading(height / 2.0, half_cells, mesh.first_cell_height_m)
    symmetric = f"( (0.5 {half_cells} {grading:.6g}) (0.5 {half_cells} {1.0 / grading:.6g}) )"

    vertices = [
        "    (0 0 0)",
        f"    ({length:.8g} 0 0)",
        f"    ({length:.8g} {height:.8g} 0)",
        f"    (0 {height:.8g} 0)",
        f"    (0 0 {width:.8g})",
        f"    ({length:.8g} 0 {width:.8g})",
        f"    ({length:.8g} {height:.8g} {width:.8g})",
        f"    (0 {height:.8g} {width:.8g})",
    ]

    return f"""
// Rectangular duct {mesh.height_m:g} x {mesh.width_m:g} x {mesh.length_m:g} m.
// Wall-normal grading {grading:.4g} (cell-to-cell ratio {cell_ratio:.3f}) at both walls.
scale   1;

vertices
(
{chr(10).join(vertices)}
);

blocks
(
    hex (0 1 2 3 4 5 6 7) ({mesh.axial_cells} {2 * half_cells} {mesh.tangential_cells})
    simpleGrading (1 {symmetric} 1)
);

edges
(
);

boundary
(
    {inlet}
    {{
        type patch;
        faces ( (0 4 7 3) );
    }}

    {outlet}
    {{
        type patch;
        faces ( (1 2 6 5) );
    }}

    {wall}
    {{
        type wall;
        faces
        (
            (0 1 5 4)
            (3 7 6 2)
            (0 3 2 1)
            (4 5 6 7)
        );
    }}
);
"""


def _wall_grading(
    thickness: float, cells: int, first_cell_height: float | None
) -> tuple[float, float]:
    """Return the blockMesh expansion ratio and the underlying per-cell ratio.

    ``simpleGrading`` takes the ratio of the last cell to the first cell, so the
    per-cell geometric ratio is solved first and then raised to ``cells - 1``. The
    per-cell ratio is returned too, because it - not the blockMesh value - decides
    whether the mesh is acceptable.
    """
    if first_cell_height is None or cells < 2:
        return 1.0, 1.0
    if first_cell_height <= 0.0 or first_cell_height * cells >= thickness:
        return 1.0, 1.0

    def total(ratio: float) -> float:
        return first_cell_height * (ratio**cells - 1.0) / (ratio - 1.0)

    low, high = 1.0 + 1.0e-9, 5.0
    while total(high) < thickness and high < 1.0e3:
        high *= 2.0
    for _ in range(200):
        middle = 0.5 * (low + high)
        if total(middle) < thickness:
            low = middle
        else:
            high = middle
    cell_ratio = 0.5 * (low + high)
    return cell_ratio ** (cells - 1), cell_ratio


def _cells_for_ratio(thickness: float, first_cell_height: float) -> int:
    """Smallest cell count that spans ``thickness`` within the accepted expansion."""
    cells = 2
    while cells < 500:
        covered = (
            first_cell_height
            * (_MAX_CELL_EXPANSION**cells - 1.0)
            / (_MAX_CELL_EXPANSION - 1.0)
        )
        if covered >= thickness:
            return cells
        cells += 1
    return cells


