"""Generate, run and read back a complete OpenFOAM case.

The case is built from CFD boundary conditions that came out of a NeqSim flash and
a geometry that came out of a design basis, so every number in the case is
traceable. Nothing is copied from a tutorial and silently edited: every dictionary
is written explicitly, which is what makes the case reviewable.

Two case types are produced:

``OpenFoamCase``
    Steady, single-phase RANS - the carrier-fluid solve behind pressure drop,
    wall shear and local velocity peaks.
``VofOpenFoamCase``
    Transient volume of fluid - two phases from one NeqSim flash with a resolved
    interface, for stratified, slug and annular flow and for free surfaces.

Two mesh generators are built in - an O-grid round duct and a rectangular duct -
and any externally generated mesh (Gmsh, Fluent, I-deas, or an existing polyMesh)
can be imported instead, so arbitrary geometry is covered.

Writing a case never requires OpenFOAM to be installed. Running it does; when the
environment is absent the run is reported as not executed rather than raising, so
the generated case can still be inspected, committed or transferred.
"""

